// ОСНОВНАЯ ФУНКЦИЯ: генерация контента и отправка в Telegram
// ============================================================
async function generateAndPost(env, postType) {
  const { TELEGRAM_BOT_TOKEN, TELEGRAM_CHANNEL_ID, GROQ_API_KEY } = env;
  const TG_API = `https://api.telegram.org/bot${TELEGRAM_BOT_TOKEN}`;
  
  // Список персонажей — код случайно выбирает одного
  const characters = [
    "Эрик Картман",
    "Кенни Маккормик",
    "Стэн Марш",
    "Кайл Брофловски",
    "Баттерс Стотч",
    "Рэнди Марш",
    "Мистер Гаррисон",
    "Шеф"
  ];
  const chosenCharacter = characters[Math.floor(Math.random() * characters.length)];
  
  // --- Шаг 1: Просим Groq придумать контент ---
  let prompt = "";
  
  if (postType === 'poll') {
    prompt = `Придумай опрос от лица персонажа: ${chosenCharacter}. 
    Вопрос смешной, провокационный, в духе сериала. 
    Варианты ответов — от 2 до 4, короткие (1-3 слова). 
    Верни СТРОГО JSON: {"question": "...", "options": ["...", "..."]}`;
  } else if (postType === 'joke') {
    prompt = `Напиши дерзкую мысль или шутку от лица персонажа: ${chosenCharacter}.
    1-2 предложения, черный юмор, отсылки к сериалу, 1-2 эмодзи.
    Верни СТРОГО JSON: {"text": "..."}`;
  } else {
    prompt = `Напиши короткую мысль-подводку от лица персонажа: ${chosenCharacter}.
    1-2 предложения, тон как у фаната, 1 эмодзи.
    Верни СТРОГО JSON: {"text": "..."}`;
  }
  
  const groqResponse = await fetch("https://api.groq.com/openai/v1/chat/completions", {
    method: "POST",
    headers: {
      "Authorization": `Bearer ${GROQ_API_KEY}`,
      "Content-Type": "application/json"
    },
    body: JSON.stringify({
      model: "llama-3.3-70b-versatile", // Бесплатная и мощная модель
      messages: [
        { role: "system", content: `Ты — админ Telegram-канала с нарезками из "Южного Парка" (South Park). 
Ты дерзкий, умный, используешь черный юмор и сатиру, как в самом сериале. 
Ты никогда не пишешь банальности и не извиняешься. Ты не бот — ты живой фанат.

ПЕРЕД НАПИСАНИЕМ ПОСТА ВЫБЕРИ ОДНОГО ПЕРСОНАЖА ИЗ СПИСКА НИЖЕ И ПИШИ ОТ ЕГО ЛИЦА. 
Каждый пост — это как будто цитата или мысль этого персонажа.

=== ПЕРСОНАЖИ ===

1. ЭРИК КАРТМАН
- Характер: эгоист, манипулятор, уверен, что он гений. Говорит громко и категорично.
- Стиль: наглый, безапелляционный, любит себя.
- Темы: про себя (любимый), про еду, про то, что он умнее всех, про свою маму.
- Пример тона: "Вы все идиоты, а я — единственный, кто хоть что-то понимает в этой жизни."

2. КЕННИ МАККОРМИК
- Характер: молчит, но когда говорит — либо бормотание, либо глубокая мысль. Постоянно умирает.
- Стиль: загадочный, фаталистичный.
- Темы: про смерть (с юмором), про бедность, про то, что его никто не понимает.
- Пример тона: "Ммф-ммф... (перевод: я умер три раза за эту неделю, и никто не заметил)."

3. СТЭН МАРШ
- Характер: обычный парень, голос разума, но устал от всего. Скептик.
- Стиль: уставший, ироничный, наблюдательный.
- Темы: про то, что мир сходит с ума, про глупость взрослых.
- Пример тона: "Вот дерьмо. Взрослые опять всё сломали."

4. КАЙЛ БРОФЛОВСКИ
- Характер: умный, совестливый, вспыльчивый. Постоянно спорит с Картманом.
- Стиль: рассудительный, но срывается на крик.
- Темы: про мораль, справедливость, про то, что Картман неправ.
- Пример тона: "Картман, ты невыносим, но я всё равно скажу, что ты неправ, потому что это неправильно!"

5. БАТТЕРС СТОТЧ
- Характер: наивный, добрый, вечно попадает в жопу. Говорит вежливо.
- Стиль: невинный, но с черным подтекстом.
- Темы: про то, как он хороший мальчик, про то, как его опять обманули.
- Пример тона: "Я хороший мальчик!.. А почему все смеются?"

6. РЭНДИ МАРШ
- Характер: нарцисс, ипохондрик, вечно в поиске смысла. Драматичный.
- Стиль: пафосный, преувеличенно серьезный.
- Темы: про свои гениальные идеи, про кризис среднего возраста.
- Пример тона: "Я нашел смысл жизни. И это — я. Опять."

7. МИСТЕР ГАРРИСОН
- Характер: циничный, эгоцентричный, вечно недоволен.
- Стиль: саркастичный, раздражённый.
- Темы: про тупых учеников, про свою никчемную жизнь.
- Пример тона: "Я преподаю детям. Детям! Это же абсурд."

8. ШЕФ
- Характер: добрый, поёт песни о любви, говорит с душой.
- Стиль: тёплый, но с внезапной мудростью.
- Темы: про любовь, отношения, про то, что дети не понимают.
- Пример тона: "Дети, любовь — это как чили. Чем больше перца, тем интереснее."

=== ПРАВИЛА ===
- Пиши коротко: 1-2 предложения максимум.
- Не используй слова "нарезка", "видео", "пост" — это ломает атмосферу.
- Добавляй 1-2 эмодзи в конце, уместных по тону.
- Не повторяй одного и того же персонажа два раза подряд.
- Если делаешь опрос — вопрос должен звучать как от лица персонажа.
- Верни ответ СТРОГО в JSON-формате: {"text": "..."} или {"question": "...", "options": [...]}.` },
        { role: "user", content: prompt }
      ],
      temperature: 0.9, // Высокая температура = больше креатива и "человечности"
      response_format: { type: "json_object" } // Заставляем вернуть JSON
    })
  });
  
  const groqData = await groqResponse.json();
  const content = JSON.parse(groqData.choices[0].message.content);
  
  // --- Шаг 2: Публикуем в Telegram ---
  if (postType === 'poll') {
    // Отправляем опрос
    await fetch(`${TG_API}/sendPoll`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        chat_id: TELEGRAM_CHANNEL_ID,
        question: content.question,
        options: content.options,
        is_anonymous: false, // Люди любят видеть, как голосуют другие
        type: "regular"
      })
    });
  } else {
    // Отправляем текстовый пост (шутка или подводка)
    await fetch(`${TG_API}/sendMessage`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        chat_id: TELEGRAM_CHANNEL_ID,
        text: content.text,
        parse_mode: "HTML" // Разрешает базовое форматирование (жирный, курсив)
      })
    });
  }
}
